/**
 * 情绪识别 —— 决定「这句话该用哪种语气念」。
 *
 * 两条路，优先走第一条：
 *
 *   ① 让 LLM 自己标。系统提示词要求她每句话开头写一个 [开心] 这样的标签。
 *      这是最准的 —— 她自己知道这句话是什么情绪，而且**零额外延迟、零额外成本**
 *      （不用再发一次请求去做分类）。
 *
 *   ② 标签没写/写歪了，就用规则兜底。关键词 + 标点，够用。
 *
 * 类别故意只留 6 个：参考音频每类要备 3~5 条才不会听着重复，
 * 类别一多，每条分到的就少了。6 类是「够表达」和「每类够厚」的平衡点。
 */

/**
 * 八大类。顺序只影响「同分时谁先被选中」，实际判定靠分数门槛。
 *
 * 为什么是这八个：
 *   最初是 6 类（把「得意」并进开心、「无奈」并进平静）。实测那个合并是错的 ——
 *   这两种语气各有 63 / 60 条素材，是芙宁娜最有辨识度的两种，塞进别的桶里两头都变味：
 *     · 撒娇式赌气「又走？你这两句话是故意气本神的吧」被判成 生气，
 *       配到的参考却是审讯腔「难不成你敢在这个地方做伪证？」
 *     · 端着架子的挑剔「哼，这种料理得不到我的认可」被当成真高兴
 *   拆开之后每个桶内部都纯了，参考音频的情绪才对得上。
 */
const CATEGORIES = ['开心', '得意', '惊讶', '生气', '难过', '温柔', '无奈', '平静']

/** 标签别名 → 正式类别。LLM 很可能写成同义词，全都收进来 */
const ALIASES = {
  开心: ['开心', '高兴', '快乐', '喜悦', '兴奋', '欢快', '愉快', '雀跃', '欣喜', 'happy', 'joy'],
  得意: ['得意', '骄傲', '自豪', '俏皮', '炫耀', '得瑟', '臭美', '卖弄', '神气', 'smug', 'proud'],
  惊讶: ['惊讶', '吃惊', '震惊', '意外', '诧异', '惊奇', '错愕', '惊', 'surprise'],
  生气: ['生气', '愤怒', '恼怒', '不爽', '不满', '恼火', '气愤', '嗔怒', 'angry'],
  难过: ['难过', '悲伤', '伤心', '低落', '沮丧', '失落', '委屈', '哀伤', 'sad'],
  温柔: ['温柔', '柔和', '关切', '宠溺', '安抚', '体贴', '温存', '暖心', 'gentle'],
  无奈: ['无奈', '无语', '苦笑', '勉强', '无可奈何', '扶额', '叹气', '认命', 'resigned'],
  平静: ['平静', '淡定', '冷静', '陈述', '平常', '寻常', '淡然', '平静地', 'neutral', 'calm'],
}

/** 反查表 */
const ALIAS_TO_CAT = (() => {
  const m = new Map()
  for (const [cat, list] of Object.entries(ALIASES)) {
    for (const a of list) m.set(a.toLowerCase(), cat)
  }
  return m
})()

/**
 * 规则兜底用的关键词。
 *
 * 每条给一个权重，命中就加权；最后看谁分高。
 * 不追求学术上的准确率 —— 它只在 LLM 忘了打标签时兜底。
 *
 * 踩过的坑：原来 难过 里有一条 `/^(……|\.\.\.)/ → +1`，
 * 意思是「以省略号开头 = 有难言之隐」。但芙宁娜大量句子就是以「……」开头的，
 * 那是她的说话习惯，不是悲伤。结果一堆闲聊被兜底判成难过。
 * 教训：**不要把标点习惯当成情绪证据**，除非那个标点本身就带情绪（比如单独一个「呜」）。
 */
const CUES = {
  开心: [
    [/(哈哈|嘿嘿|嘻嘻|噗嗤|啊哈)/, 3],
    [/(太好了|好耶|真棒|不错嘛|有意思|好玩|喜欢|开心|高兴|乐意|期待)/, 2],
  ],
  得意: [
    [/(哼哼|怎么样|厉害吧|了不起吧|佩服吧|羡慕吧)/, 3],
    // 这些词在她的语料里几乎只出现在「端着架子」的时候，单独一条就够判
    [/(本神可是|我可是|早就知道|一眼就看穿|小意思|不在话下|轻而易举|小事一桩|手到擒来|世面|见识)/, 3],
    [/(当然|自然|毕竟|大明星|了不起)/, 2],
  ],
  惊讶: [
    [/(怎么可能|竟然|居然|真的假的|不会吧|天哪|天啊|什么[？?！!])/, 3],
    [/(咦|诶|欸|哎哟|哇[！!]?|呀[！!])/, 2],
    [/(想不到|没想到|骗人)/, 2],
  ],
  生气: [
    [/(哼[！!]|讨厌|过分|岂有此理|不可原谅|少来|别闹)/, 3],
    [/(生气|恼怒|烦人|无礼|放肆|混账|唱反调)/, 3],
    [/(才不|凭什么|谁要|懒得)/, 2],
  ],
  难过: [
    [/(对不起|抱歉)/, 3],
    [/(难过|伤心|寂寞|孤独|痛苦|泪水|哭泣|委屈)/, 3],
    [/(遗憾|可惜|失落)/, 2],
  ],
  温柔: [
    [/(晚安|早点休息|辛苦了|别担心|慢慢来|没关系|我陪着|我会一直在)/, 3],
    [/(要好好|照顾好自己|别太累|歇一歇|喝口水|明天见)/, 2],
  ],
  // 无奈要的是「放弃抵抗」的意味，门槛给到 3 —— 「好吧」这种
  // 单独出现太常见（可能只是普通应答），不能只凭它就判无奈
  无奈: [
    [/(算了|没办法|无可奈何|真是的|无语|服了|头疼|认命)/, 3],
    [/(行吧|随你|随便你|唉|啧)/, 2],
  ],
  平静: [
    [/(原来如此|是这样|好的|知道了|嗯[，。]|确实|明白了)/, 2],
  ],
}

/**
 * 每类要多少分才敢认。
 *
 * 这是「不对称损失」：判错的代价不一样。
 *   · 把闲聊判成平静 —— 几乎没代价，本来就该是平静
 *   · 把闲聊判成难过/生气 —— 参考音频会把整句话念成哀乐或吵架，非常出戏
 * 所以平静的门槛是 0（本来就是默认值），而带强烈情绪的类别要求 3 分以上。
 */
const MIN_SCORE = {
  平静: 0,
  温柔: 2,
  开心: 2,
  无奈: 3,
  得意: 3,
  惊讶: 3,
  生气: 3,
  难过: 3,
}

/** 去掉 LLM 可能带上的 markdown / 前缀噪声 */
function sanitize(text) {
  return String(text || '')
    .replace(/\r/g, '')
    .trim()
}

/**
 * 去掉正文里**所有位置**的情绪标签，不只是句首那个。
 *
 * 为什么需要它（实测踩到的）：
 *   `extractTag` 只认句首的标签 —— 这是对的，正文中间的方括号是剧情内容。
 *   但模型有时候会在**一轮回复中间**又打一个标签，比如
 *       [温柔]好，那就不说。*她没再说什么。*[平静]陪你待着也行。
 *   第二个标签既不在句首（前面有旁白），又确实是个情绪标签。
 *   它就这么漏进了送去合成的那段文本里 —— 用户会听见她念「方括号 平静 方括号」。
 *
 * 判据比 extractTag 更保守：括号内容必须**确实是一个已知情绪词**才删，
 * 所以正文里的 `[注]`、`[1]`、`[重要]` 都留着。
 */
function stripAllTags(text) {
  return String(text || '').replace(/[[【（(]\s*([^\]】)）\n]{1,6}?)\s*[\]】)）]/g, (m, inner) => {
    return ALIAS_TO_CAT.has(String(inner).trim().toLowerCase()) ? '' : m
  })
}

/**
 * 从回复里抠出情绪标签。
 *
 * 认这几种写法（都在句首）：
 *   [开心] 正文
 *   【开心】正文
 *   （开心）正文
 *   [开心]: 正文
 * 也认标签单独占一行的情况。
 *
 * @returns {{category: string|null, cleaned: string, raw: string|null}}
 */
function extractTag(text) {
  const t = sanitize(text)
  // 只认句首 —— 正文中间出现的方括号是剧情内容，不能当成标签吃掉
  const m = t.match(/^\s*[[【（(]\s*([^\]】)）\n]{1,6}?)\s*[\]】)）]\s*[:：,，。.、-]?\s*/)
  if (!m) return { category: null, cleaned: t, raw: null }

  const raw = m[1].trim()
  const cat = ALIAS_TO_CAT.get(raw.toLowerCase())
  if (!cat) return { category: null, cleaned: t, raw: null }

  return { category: cat, cleaned: t.slice(m[0].length).trim() || t, raw }
}

/**
 * 规则兜底：关键词打分。
 *
 * 除了算分，还要过 MIN_SCORE 那道门槛 —— 证据不够就认怂用「平静」。
 * 这是刻意的偏保守：漏判成平静只是少了一点色彩，误判成难过是整句话都毁了。
 *
 * @returns {string} 六大类之一，永远有返回值
 */
function guessEmotion(text) {
  const t = sanitize(text)
  if (!t) return '平静'

  const scores = {}
  for (const cat of CATEGORIES) {
    let score = 0
    for (const [re, w] of CUES[cat] || []) {
      // 统计命中次数，命中多次说明语气更强
      const hits = (t.match(new RegExp(re.source, 'g')) || []).length
      if (hits) score += w * Math.min(hits, 3)
    }
    // 叹号多 = 情绪外放，问号多 = 偏惊讶/疑问
    if (cat === '惊讶' && /[？?]/.test(t)) score += 1
    if ((cat === '开心' || cat === '生气') && /[！!]/.test(t)) score += 1
    scores[cat] = score
  }

  // 只在「自己那道门槛」过线的类别里挑最高分
  let best = '平静'
  let bestScore = 0
  for (const cat of CATEGORIES) {
    const s = scores[cat]
    if (s < (MIN_SCORE[cat] ?? 2)) continue
    if (s > bestScore) {
      bestScore = s
      best = cat
    }
  }
  return best
}

/**
 * 统一入口：先看标签，再兜底。
 *
 * @param {string} text  LLM 的原始回复
 * @returns {{category:string, cleaned:string, source:'tag'|'rule', raw:string|null}}
 */
function resolveEmotion(text) {
  const { category, cleaned, raw } = extractTag(text)
  if (category) return { category, cleaned, source: 'tag', raw }
  const t = sanitize(text)
  return { category: guessEmotion(t), cleaned: t, source: 'rule', raw: null }
}

/** 写进系统提示词的那段说明 —— 放这里，改类别时不用去翻 main.js */
function promptRule() {
  // 放在系统提示词的最后一段：越靠后越不容易被忽略（实测漏标率明显下降）
  return [
    '【输出格式 · 必须遵守】',
    `你每次回复的**第一个字符**必须是情绪标签，格式为方括号包住一个词，只能从这八个里选：${CATEGORIES.map((c) => `[${c}]`).join('')}。`,
    '标签后面直接接着说话，中间不要换行、不要空格、不要解释这个标签。',
    '',
    '每个标签什么时候用：',
    '[平静] 日常闲聊、陈述事实、随口应答、解释说明 —— **拿不准就用这个**',
    '[开心] 真的高兴、被逗乐、心情好、期待什么好事',
    '[得意] 端着架子、炫耀、俏皮地挑衅、对自己很满意（「这种程度的谜题，一眼就看穿了」）',
    '[温柔] 关心对方、安慰、把语气放柔',
    '[无奈] 无语、放弃抵抗、勉为其难、叹气（「算了」「唉」「行吧」「随你」）',
    '[生气] 真的不满、被惹到、跟对方拌嘴',
    '[难过] 失落、委屈、感伤 —— 这个标签很重，只有真的情绪低落时才用',
    '[惊讶] 意外、吃惊、没料到',
    '',
    '[得意] 和 [生气] 的区别：得意是**你占上风**（炫耀、俏皮地挤兑），生气是**你被惹到**。',
    '撒娇式的小脾气（「哼，你终于想起我啦」）用 [得意] 或 [开心]，不要用 [生气]。',
    '',
    '正确示例：',
    '[开心]嘿嘿，你终于来啦！',
    '[得意]这种程度的谜题，本神一眼就看穿了。',
    '[温柔]累了就歇会儿吧，我陪着你。',
    '[无奈]好吧好吧，那就听你的。',
    '[生气]喂，你搞清楚，这可不是让你找架打的地方！',
    '[惊讶]诶？这是什么时候弄的？',
    '[平静]嗯，我在听，你说吧。',
    '',
    '错误示例（不要这样）：',
    '（缺少标签）嘿嘿，你终于来啦！',
    '（标签和内容分了两行）[开心]\\n嘿嘿，你终于来啦！',
    '（用了列表以外的词）[兴奋]嘿嘿！',
    '（把普通闲聊标成难过）[难过]嗯，我在听。',
    '',
    '最重要的一条：**普通对话就是[平静]**。不要因为句子开头有省略号「……」、',
    '或者内容提到累/忙/难，就标成[难过] —— 那只是普通的说话方式。',
    '这个标签决定你用哪种语气说话，标错了语气就会配错，所以每一句都必须有，而且要贴切。',
  ].join('\n')
}

module.exports = { CATEGORIES, ALIASES, resolveEmotion, extractTag, stripAllTags, guessEmotion, promptRule, ALIAS_TO_CAT }
