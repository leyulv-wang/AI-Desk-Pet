/**
 * 从角色扮演回复里挑出「该念出来的部分」
 *
 * ─────────────────────────────────────────────────────────────────────
 * 为什么需要它
 * ─────────────────────────────────────────────────────────────────────
 * 桌宠改成角色扮演之后，她的回复会长这样：
 *
 *     *她把茶杯推到一边，指尖在杯沿上敲了两下。*
 *     「你回来啦。」*她抬眼看了看你，又飞快地移开。*
 *     「今天的蛋糕我留了一块——别误会，是买多了。」
 *
 * 屏幕上这样很好看。但这条流水线的终点是**扬声器**：
 * 全念出来的话，用户听到的是
 * 「星号 她把茶杯推到一边 星号 你回来啦 星号 她抬眼看了看你…」
 * —— 星号会被念出来，旁白用第三人称描述她自己的动作更是荒唐。
 *
 * 所以：**文字层放开写，语音层只念对白。**
 * 上面那段到她嘴里只剩「你回来啦。」和「今天的蛋糕我留了一块——别误会，是买多了。」
 *
 * ─────────────────────────────────────────────────────────────────────
 * 为什么是「剥星号」而不是「抽引号」
 * ─────────────────────────────────────────────────────────────────────
 * 直觉做法是「只念引号里的」。但流式下这个判断很难做对：
 * 回复常常**先写一段旁白再开口**，而旁白到的时候我们还不知道后面有没有引号 ——
 * 要么先憋着不出声（首句延迟变长），要么赌一把（赌错就把旁白念了）。
 *
 * 改成「旁白必须用 *星号* 包起来，其余都是要念的」，问题就没了：
 *   · 逐字符就能判，不需要预读
 *   · 跨段的星号也能靠一个 inStar 标志接上
 *   · 引号只是**写法**，剥掉就行（「你回来啦。」→ 你回来啦。）
 *
 * 代价是人设里必须硬性要求「旁白一律用星号」—— 这条写进了 characters/furina.json 的
 * 【旁白与对白】段。人设漏了这条，这里就会把旁白念出来。
 */

/** 成对的引号，念的时候剥掉外壳只留内容 */
const QUOTE_CHARS = /[「」『』“”„‟"]/g

/**
 * 纯函数版：一段文本 → 该念的部分（可能为空串）。
 * 不处理跨段的星号，给测试和非流式场景用。
 */
function spokenOf(text) {
  const ex = createSpokenExtractor()
  const parts = [...ex.push(text), ...ex.flush()]
  return parts.join('')
}

/**
 * 流式版：一段一段喂进来，吐出该念的片段。
 *
 * 唯一的状态是 `inStar` —— 因为 `*旁白*` 可能被切句器切开，
 * 前半段在上一句、后半段在下一句，状态必须跨段保持。
 */
function createSpokenExtractor() {
  let inStar = false
  /** 连续星号的计数。`*动作*` 和 `**动作**` 都要当成一对，所以「一串星号」只算一次开关 */
  let starRun = 0
  let acc = ''

  function flushAcc() {
    const s = acc.replace(QUOTE_CHARS, '').replace(/\s+/g, ' ').trim()
    acc = ''
    // 只剩标点的片段没有念的价值（旁白被剥干净时会剩下句号）
    if (!s || !/[\p{L}\p{N}]/u.test(s)) return null
    return s
  }

  function push(text) {
    const out = []
    for (const ch of String(text || '')) {
      if (ch === '*') {
        starRun++
        continue
      }
      // 星号串结束 —— 奇偶都算一次开关（`*` 和 `**` 都是包一对旁白）
      if (starRun > 0) {
        inStar = !inStar
        starRun = 0
      }
      if (!inStar) acc += ch
    }
    const s = flushAcc()
    if (s) out.push(s)
    return out
  }

  /** 流结束：收尾。还有没闭合的星号就当它是普通文字，别把后半段整段吞掉 */
  function flush() {
    if (starRun > 0) {
      inStar = !inStar
      starRun = 0
    }
    const s = flushAcc()
    return s ? [s] : []
  }

  return { push, flush, reset: () => { inStar = false; starRun = 0; acc = '' } }
}

module.exports = { createSpokenExtractor, spokenOf }
